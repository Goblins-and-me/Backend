package com.shop.SweetStory.order.entity;

import com.shop.SweetStory.auth.entity.User;
import com.shop.SweetStory.catalog.entity.Product;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;

/**
 * JPA entity representing an order, mapped to the {@code orders} table.
 * Contains information about the delivery date, associated {@link Product} and customer {@link User},
 * customization options, weight, price, and current {@link OrderStatus}.
 */
@Entity
@Table(name = "orders")
@NoArgsConstructor
@AllArgsConstructor
@Setter
@Getter
public class Order {

    /**
     * Primary key of the order, generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Scheduled delivery date for the order (required field).
     */
    @Column(name = "delivery_date", nullable = false)
    private LocalDate deliveryDate;

    /**
     * Ordered product from the catalog (required many-to-one association with lazy fetching).
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "product_id", nullable = false)
    private Product product;

    /**
     * User who placed the order (required many-to-one association with lazy fetching).
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /**
     * Selected filling for the item.
     */
    @Column(name = "filling")
    private String filling;

    /**
     * Selected design or decoration option for the item.
     */
    @Column(name = "decor")
    private String decor;

    /**
     * Weight of the ordered item (required field).
     */
    @Column(name = "weight", nullable = false)
    private Double weight;

    /**
     * Total order price with a precision of 12 digits and a scale of 2 decimal places.
     */
    @Column(name = "order_price", nullable = false, precision = 12, scale = 2)
    private BigDecimal orderPrice;

    /**
     * Current order status, persisted in the database as the {@link OrderStatus} enum string name.
     * Defaults to {@link OrderStatus#PENDING}.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "order_status", nullable = false)
    private OrderStatus status = OrderStatus.PENDING;
}